"""Data audit of the Skylit replay archive against UW 1-minute bars. Describes the data; makes no trading claim.

For every replay file: session status, frames kept/dropped, whether expirations[0] is the session date, and how the
replay spot compares with the UW bar that closed at the frame timestamp (prior bar) versus the bar that opens there.
Writes reports/DATA_AUDIT.json and reports/DATA_AUDIT.md through the run ledger.

    python -m gammalab.audit_replay
"""
from __future__ import annotations

import json
import statistics as st
from datetime import date, datetime, timedelta

from .adapters import skylit_replay, uw_m1
from .contract.calendar import session
from .runlog import ROOT, Run

UW_SYM = {"SPY": "SPY", "QQQ": "QQQ"}   # SPXW has no stock bars in the cache; spot checks use SPY/QQQ only


def audit_file(p):
    raw = json.loads(p.read_text())
    day = date.fromisoformat(raw["metadata"]["date"])
    row = {"file": p.name, "date": day.isoformat(), "weekday": day.strftime("%a"), "frames": len(raw["frames"]),
           "session": session(day) is not None, "scrapedAt": raw["metadata"].get("scrapedAt")}
    if not row["session"]:
        return row
    snaps = skylit_replay.load_day(p, lag=timedelta(0))
    row["snapshots_kept"] = len(snaps)
    row["front_is_0dte"] = sum(s.expirations[0] == row["date"] for s in snaps) / max(len(snaps), 1)
    row["front_rolled"] = sorted({f"{s.symbol} {s.provider_ts:%H:%M}" for s in snaps if s.expirations[0] > row["date"]})
    row["compact_expiry_format"] = sum(1 for f in raw["frames"] for t in f.get("tickers", {}).values()
                                      if t and t.get("expirations") and "-" not in t["expirations"][0])
    first = next((f for f in raw["frames"] if f["timestamp"].startswith(f"{day}T14:30") or f["timestamp"].startswith(f"{day}T13:30")), None)
    for sym, usym in UW_SYM.items():
        bars = {b.ts_open: b for b in uw_m1.load_day(usym, row["date"])}
        if not bars:
            continue
        prev, cur = [], []
        for s in (x for x in snaps if x.symbol == sym):
            b0, b1 = bars.get(s.provider_ts - timedelta(minutes=1)), bars.get(s.provider_ts)
            if b0: prev.append(abs(s.spot - b0.c))
            if b1: cur.append(abs(s.spot - b1.c))
        row[f"{sym}_med_abs_vs_prior_bar_close"] = round(st.median(prev), 4) if prev else None
        row[f"{sym}_med_abs_vs_same_minute_bar_close"] = round(st.median(cur), 4) if cur else None
        if first and sym in first["tickers"]:
            o = min(bars)
            row[f"{sym}_open_frame_spot"] = first["tickers"][sym]["spotPrice"]
            row[f"{sym}_first_bar_open"] = bars[o].o
    return row


def main():
    files = sorted(skylit_replay.DATA.glob("gex-replay-*.json"))
    with Run("audit_replay", inputs=files) as run:
        rows = [audit_file(p) for p in files]
        out = ROOT / "reports" / "DATA_AUDIT.json"
        out.write_text(json.dumps(rows, indent=1))
        run.output(out)
        md = ROOT / "reports" / "DATA_AUDIT.md"
        sess = [r for r in rows if r["session"]]
        lines = ["# Replay data audit", "", f"Generated by `python -m gammalab.audit_replay` (see runs/LEDGER.jsonl for SHA and input hashes).", "",
                 f"- files: {len(rows)}; trading-day files: {len(sess)}; non-session files (excluded): "
                 + ", ".join(f"{r['date']} ({r['weekday']})" for r in rows if not r["session"]),
                 f"- snapshots kept (SPXW+SPY+QQQ, in-session frames only): {sum(r['snapshots_kept'] for r in sess)}",
                 f"- empty trading-day files (0 frames): " + (", ".join(r["date"] for r in sess if r["frames"] == 0) or "none"),
                 f"- symbol-frames with expirations written YYYYMMDD (normalized by the adapter): "
                 + str(sum(r["compact_expiry_format"] for r in sess)),
                 f"- frames where the 0DTE column had already rolled off (front = next day; `front` selection refuses them): "
                 + ("; ".join(f"{r['date']} " + ", ".join(r["front_rolled"]) for r in sess if r["front_rolled"]) or "none"),
                 f"- days where expirations[0] is not always the session date after normalization: "
                 + (", ".join(r["date"] for r in sess if r["front_is_0dte"] < 1 and r["frames"]) or "none"), ""]
        for sym in UW_SYM:
            a = [r[f"{sym}_med_abs_vs_prior_bar_close"] for r in sess if r.get(f"{sym}_med_abs_vs_prior_bar_close") is not None]
            b = [r[f"{sym}_med_abs_vs_same_minute_bar_close"] for r in sess if r.get(f"{sym}_med_abs_vs_same_minute_bar_close") is not None]
            if a:
                lines.append(f"- {sym} spot vs UW close, median over days of the daily median |diff|: bar ending at frame time "
                             f"{st.median(a):.3f}; bar starting at frame time {st.median(b):.3f} ({len(a)} days)")
            gaps = [abs(r[f"{sym}_open_frame_spot"] - r[f"{sym}_first_bar_open"]) for r in sess if f"{sym}_open_frame_spot" in r]
            if gaps:
                lines.append(f"- {sym} 09:30 frame spot vs first regular bar open, median |diff| {st.median(gaps):.3f} "
                             f"(max {max(gaps):.3f}): the 09:30 frame is dropped by the adapter")
        lines += ["", "Per-file detail: reports/DATA_AUDIT.json."]
        md.write_text("\n".join(lines) + "\n")
        run.output(md)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
